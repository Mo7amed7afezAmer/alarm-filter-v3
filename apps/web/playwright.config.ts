import { execFileSync } from "node:child_process";
import { copyFileSync, existsSync, mkdirSync, writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";
import { defineConfig, devices } from "@playwright/test";
import { loadEnv } from "vite";

// NFR-42: Playwright smoke tests against `next dev` on :3200, using alarms_test (NFR-41).
const root = fileURLToPath(new URL("../..", import.meta.url));
const env = loadEnv("", root, "");
const PORT = 3200;
const baseURL = `http://localhost${":"}${PORT}`;
/** G-T14 timing runs against a production build (decided 2026-10-17). */
const PROD_PORT = 3201;
const PROD_URL = `http://localhost${":"}${PROD_PORT}`;

if (!env.TEST_DATABASE_URL) throw new Error("TEST_DATABASE_URL is required for the e2e tests");
process.env.TEST_DATABASE_URL = env.TEST_DATABASE_URL;

// Hourly reports come from a local folder (HOURLY_GMAIL_MOCK_DIR): the real report RAR and XLSX of
// samples/hourly, plus a ~40k-row RAR built here for the timing budget (G-T14) when WinRAR/rar exists.
const mockDir = fileURLToPath(new URL("./.e2e-hourly/", import.meta.url));
mkdirSync(mockDir, { recursive: true });
for (const f of ["nsn-update-output.rar", "nsn-update-output.xlsx"]) copyFileSync(`${root}/samples/hourly/${f}`, mockDir + f);
const RAR = ["C:/Program Files/WinRAR/Rar.exe", "/usr/bin/rar", "/usr/local/bin/rar"].find((p) => existsSync(p));
if (RAR && !existsSync(mockDir + "report-40k.rar")) {
  execFileSync(process.execPath, [fileURLToPath(new URL("./e2e/make-40k.cjs", import.meta.url)), mockDir + "report-40k.xlsx"]);
  execFileSync(RAR, ["a", "-ma5", "-ep", "-idq", mockDir + "report-40k.rar", mockDir + "report-40k.xlsx"]);
}
writeFileSync(mockDir + "README.txt", "Generated by playwright.config.ts for the e2e tests.\n");
execFileSync(process.execPath, [fileURLToPath(new URL("./scripts/copy-unrar-wasm.mjs", import.meta.url))]);

function serverEnv(url: string, distDir: string): Record<string, string> {
  return {
    ...env,
    DATABASE_URL: env.TEST_DATABASE_URL!,
    NEXTAUTH_URL: url,
    NEXTAUTH_SECRET: env.NEXTAUTH_SECRET || "e2e-secret",
    GMAIL_LABELS: "DN/Kafr ElDawar",
    NEXT_DIST_DIR: distDir,
    HOURLY_GMAIL_MOCK_DIR: mockDir,
  };
}

export default defineConfig({
  testDir: "./e2e",
  globalSetup: "./e2e/global-setup.ts",
  timeout: 180_000,
  workers: 1,
  use: { baseURL, trace: "retain-on-failure", acceptDownloads: true },
  projects: [{ name: "chromium", use: { ...devices["Desktop Chrome"] } }],
  webServer: [
    {
      command: `node node_modules/next/dist/bin/next dev -p ${PORT}`,
      url: `${baseURL}/login`,
      timeout: 300_000,
      reuseExistingServer: false,
      env: serverEnv(baseURL, ".next-e2e"),
    },
    {
      command: `node node_modules/next/dist/bin/next build && node node_modules/next/dist/bin/next start -p ${PROD_PORT}`,
      url: `${PROD_URL}/login`,
      timeout: 900_000,
      reuseExistingServer: false,
      env: serverEnv(PROD_URL, ".next-e2e-prod"),
    },
  ],
});
